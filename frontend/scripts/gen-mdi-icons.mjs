#!/usr/bin/env node
// Generates the MDI icon tables the hub ships:
//   frontend/src/lib/data/mdi-icons.js          (Admin UI icon search, lazy chunk)
//   halumar/rootfs/opt/hub/data/mdi_paths.py     (hub: mdi:<name> -> icon_svg)
//
// Source: @mdi/js (paths) and @mdi/svg/meta.json (names, tags) of the same version.
// Icons in the category "Brand / Logo" and deprecated icons are left out: the
// Pictogrammers Free License does not cover them ("Brand and Logo icons are
// deprecated and being removed for legal reasons",
// https://pictogrammers.com/docs/general/license/). Their names are kept in
// REMOVED_MDI_ICONS so stored values fall back to a neutral icon.
//
//   node scripts/gen-mdi-icons.mjs           write both files
//   node scripts/gen-mdi-icons.mjs --check   exit 1 if a file is out of date (CI)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const require = createRequire(import.meta.url);
const FRONTEND = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const JS_OUT = resolve(FRONTEND, 'src/lib/data/mdi-icons.js');
const PY_OUT = resolve(FRONTEND, '../halumar/rootfs/opt/hub/data/mdi_paths.py');
const BRAND_TAG = 'Brand / Logo';
const FALLBACK = 'shape-outline';

const jsPkg = require('@mdi/js/package.json');
const svgPkg = require('@mdi/svg/package.json');
if (jsPkg.version !== svgPkg.version) {
	console.error(`@mdi/js ${jsPkg.version} and @mdi/svg ${svgPkg.version} differ; pin both to the same version.`);
	process.exit(1);
}
const paths = await import('@mdi/js');
const meta = JSON.parse(readFileSync(require.resolve('@mdi/svg/meta.json'), 'utf8'));

const camel = (name) => 'mdi' + name.split('-').map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
const removedReason = (icon) => (icon.tags || []).includes(BRAND_TAG) || icon.deprecated;

const kept = [];
const removed = [];
for (const icon of [...meta].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
	if (removedReason(icon)) {
		removed.push(icon.name);
		continue;
	}
	const d = paths[camel(icon.name)];
	if (typeof d !== 'string') {
		console.error(`@mdi/js has no path for ${icon.name}`);
		process.exit(1);
	}
	kept.push([icon.name, d]);
}
if (!kept.some(([n]) => n === FALLBACK)) {
	console.error(`fallback icon ${FALLBACK} is missing`);
	process.exit(1);
}

const v = jsPkg.version;
const js =
	`// Auto-generated by scripts/gen-mdi-icons.mjs from @mdi/js v${v} — ${kept.length} icons\n` +
	`// (without the ${removed.length} "${BRAND_TAG}" and deprecated icons, see the script)\n` +
	'// Format: [kebab-name, svg-path-d]\n' +
	'export default [\n' +
	kept.map(([n, d]) => JSON.stringify([n, d]) + ',\n').join('') +
	'];\n';

const py =
	`"""Auto-generated MDI icon SVG paths from @mdi/js v${v} (scripts/gen-mdi-icons.mjs).\n` +
	'\n' +
	`${kept.length} icons. Used by the hub to send icon_svg for mdi:<name> values.\n` +
	'Key format: kebab-case name without mdi: prefix.\n' +
	'Value: SVG path d-attribute string.\n' +
	'\n' +
	`Icons tagged "${BRAND_TAG}" in @mdi/svg meta.json and deprecated icons are not\n` +
	'included: the Pictogrammers Free License does not cover them. Stored values that\n' +
	'name one of them resolve to FALLBACK_MDI_ICON.\n' +
	'"""\n' +
	'\n' +
	`FALLBACK_MDI_ICON = "${FALLBACK}"\n` +
	'\n' +
	'REMOVED_MDI_ICONS: frozenset[str] = frozenset(\n' +
	'    {\n' +
	removed.map((n) => `        ${JSON.stringify(n)},\n`).join('') +
	'    }\n' +
	')\n' +
	'\n' +
	'MDI_PATHS: dict[str, str] = {\n' +
	kept.map(([n, d]) => `    ${JSON.stringify(n)}: ${JSON.stringify(d)},\n`).join('') +
	'}\n' +
	'\n' +
	'\n' +
	'def get_mdi_path(name: str, *, fallback: bool = True) -> str | None:\n' +
	'    """Get SVG path for an MDI icon by kebab-case name (without mdi: prefix).\n' +
	'\n' +
	'    Accepts bare names like "home", "sofa", "lightbulb" and "mdi:home".\n' +
	'    Returns the SVG path d-attribute string or None if unknown. A removed\n' +
	'    brand/deprecated icon resolves to FALLBACK_MDI_ICON unless fallback=False.\n' +
	'    """\n' +
	'    if not name:\n' +
	'        return None\n' +
	'    # Accept both "mdi:home" and "home" for convenience\n' +
	'    if name.startswith("mdi:"):\n' +
	'        name = name[4:]\n' +
	'    path = MDI_PATHS.get(name)\n' +
	'    if path is None and fallback and name in REMOVED_MDI_ICONS:\n' +
	'        return MDI_PATHS[FALLBACK_MDI_ICON]\n' +
	'    return path\n';

const check = process.argv.includes('--check');
let stale = false;
for (const [file, content] of [
	[JS_OUT, js],
	[PY_OUT, py],
]) {
	let current = null;
	try {
		current = readFileSync(file, 'utf8');
	} catch {
		current = null;
	}
	if (current === content) continue;
	if (check) {
		console.error(`${file} is out of date: run npm run icons`);
		stale = true;
	} else {
		writeFileSync(file, content);
		console.log(`wrote ${file}`);
	}
}
console.log(`@mdi/js ${v}: ${kept.length} icons, ${removed.length} brand/deprecated icons left out`);
process.exit(stale ? 1 : 0);
